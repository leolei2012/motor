/** ─────────────────────────────────────────────
 * 初始化
 * ───────────────────────────────────────────── */

int8_t ntc_init(struct ntc_handle_t *h, uint16_t adc_max, const struct ntc_table_entry_t *table, uint16_t table_len)
{
    if (h == NULL || table == NULL || table_len < 2)
    {
        return NTC_ERR_NULL;
    }

    h->adc_max = adc_max;
    h->table = table;
    h->table_len = table_len;

    h->_initialized = 1;

    return NTC_OK;
}

/** ─────────────────────────────────────────────
 * AD → 温度（二分查找 + 线性插值）
 * ───────────────────────────────────────────── */

int8_t ntc_ad_to_temp(const struct ntc_handle_t *h, uint16_t ad_raw, int16_t *temp_x10)
{
    const struct ntc_table_entry_t *tbl;
    uint16_t len;
    uint16_t lo, hi;
    uint16_t mid;
    uint8_t ascending;

    int32_t ad1;
    int32_t ad2;
    int32_t t1;
    int32_t t2;
    int32_t ad;
    int32_t delta_ad;

    if (h == NULL || temp_x10 == NULL || h->table == NULL || h->table_len < 2)
    {
        return NTC_ERR_NULL;
    }

    tbl = h->table;
    len = h->table_len;

    ascending = (tbl[0].ad < tbl[len - 1].ad) ? 1 : 0;

    /** 超出表范围检查 */
    if ((ascending && ad_raw < tbl[0].ad) || (!ascending && ad_raw > tbl[0].ad))
    {
        *temp_x10 = tbl[0].temp_x10;
        return NTC_ERR_TEMP_RANGE;
    }
    if ((ascending && ad_raw > tbl[len - 1].ad) || (!ascending && ad_raw < tbl[len - 1].ad))
    {
        *temp_x10 = tbl[len - 1].temp_x10;
        return NTC_ERR_TEMP_RANGE;
    }

    /// 二分查找
    lo = 0;
    hi = len - 1;
    while (hi - lo > 1)
    {
        mid = (lo + hi) >> 1;
        if ((ascending && tbl[mid].ad <= ad_raw) || (!ascending && tbl[mid].ad >= ad_raw))
        {
            lo = mid;
        }
        else
        {
            hi = mid;
        }
    }

    /// 线性插值
    ad1 = (int32_t)tbl[lo].ad;
    ad2 = (int32_t)tbl[hi].ad;
    t1 = (int32_t)tbl[lo].temp_x10;
    t2 = (int32_t)tbl[hi].temp_x10;
    ad = (int32_t)ad_raw;

    delta_ad = ad2 - ad1;

    if (delta_ad == 0)
    {
        *temp_x10 = (int16_t)t1;
        return NTC_OK;
    }

    /// T = T1 + (T2 - T1) * (AD - AD1) / (AD2 - AD1)
    *temp_x10 = (int16_t)(t1 + (t2 - t1) * (ad - ad1) / delta_ad);

    return NTC_OK;
}

int8_t ntc_get_temp(struct ntc_handle_t *h, uint16_t adc_raw, int16_t *temp_x10)
{
    if (h == NULL || temp_x10 == NULL || !h->_initialized)
    {
        return NTC_ERR_NULL;
    }

    /// ── 2. ADC 边界检查
    if (adc_raw == 0 || adc_raw >= h->adc_max)
    {
        *temp_x10 = NTC_TEMP_INVALID;
        return NTC_ERR_ADC_RANGE;
    }

    return ntc_ad_to_temp(h, adc_raw, temp_x10);
}